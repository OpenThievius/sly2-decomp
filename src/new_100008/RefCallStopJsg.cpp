#include "sly2.h"
#include "cref.h"
CRef RefSetArgsFromSplice(int cref, CRef *aref, const void *aotyp, ...);
struct JSG;
extern "C" void StopJsg(JSG *);

extern "C" CRef RefCallStopJsg(JSG *object, int count, CRef *args)
{
    RefSetArgsFromSplice(0, args, 0);
    CRef refResult;
    refResult.SetTag(TAGK_Void);
    StopJsg(object);
    return refResult;
}
