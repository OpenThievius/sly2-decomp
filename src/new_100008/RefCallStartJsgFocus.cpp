#include "sly2.h"
#include "cref.h"
CRef RefSetArgsFromSplice(int cref, CRef *aref, const void *aotyp, ...);
struct JSG;
extern "C" void StartJsgFocus(JSG *);

extern "C" CRef RefCallStartJsgFocus(JSG *object, int count, CRef *args)
{
    RefSetArgsFromSplice(0, args, 0);
    CRef refResult;
    refResult.SetTag(TAGK_Void);
    StartJsgFocus(object);
    return refResult;
}
