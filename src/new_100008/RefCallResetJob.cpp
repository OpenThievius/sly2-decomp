#include "sly2.h"
#include "cref.h"
CRef RefSetArgsFromSplice(int cref, CRef *aref, const void *aotyp, ...);
struct JOB;
extern "C" void ResetJob(JOB *);

extern "C" CRef RefCallResetJob(JOB *object, int count, CRef *args)
{
    RefSetArgsFromSplice(0, args, 0);
    CRef refResult;
    refResult.SetTag(TAGK_Void);
    ResetJob(object);
    return refResult;
}
