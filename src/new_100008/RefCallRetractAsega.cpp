#include "sly2.h"
#include "cref.h"
CRef RefSetArgsFromSplice(int cref, CRef *aref, const void *aotyp, ...);
struct ASEGA;
extern "C" void RetractAsega(ASEGA *);

extern "C" CRef RefCallRetractAsega(ASEGA *object, int count, CRef *args)
{
    RefSetArgsFromSplice(0, args, 0);
    CRef refResult;
    refResult.SetTag(TAGK_Void);
    RetractAsega(object);
    return refResult;
}
