#include "sly2.h"
#include "cref.h"
CRef RefSetArgsFromSplice(int cref, CRef *aref, const void *aotyp, ...);
struct SND;
extern "C" void StopStream(SND *);

extern "C" CRef RefCallStopStream(SND *object, int count, CRef *args)
{
    RefSetArgsFromSplice(0, args, 0);
    CRef refResult;
    refResult.SetTag(TAGK_Void);
    StopStream(object);
    return refResult;
}
